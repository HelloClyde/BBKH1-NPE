"""Regenerate the Chinese H1 menu bitmap from pinned Noto Sans CJK SC."""
import argparse
import hashlib
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
FONT_SHA256 = '2c76254f6fc379fddfce0a7e84fb5385bb135d3e399294f6eeb6680d0365b74b'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--font', type=Path, required=True)
    args = parser.parse_args()
    assert hashlib.sha256(args.font.read_bytes()).hexdigest() == FONT_SHA256, 'Wrong font revision'
    font = ImageFont.truetype(str(args.font), 18)
    source = ''.join(path.read_text(encoding='utf-8') for path in sorted((ROOT/'src/platform').glob('*.c')))
    chars = sorted(set(map(chr, range(32, 127))) | {c for c in source if ord(c) >= 128})
    out = ['/* Noto Sans CJK SC rendered glyph subset; OFL 1.1.',
           ' * See assets/licenses/NotoSansCJK-OFL.txt and assets/README.md.',
           ' * Generated by tools/generate_menu_font.py; 18 px, baseline 18. */',
           '#ifndef H1_MENU_FONT_H', '#define H1_MENU_FONT_H',
           'static const struct { uint32_t code, advance, rows[21]; } menu_glyphs[] = {']
    for char in chars:
        bitmap = Image.new('L', (18, 21))
        ImageDraw.Draw(bitmap).text((0, 18), char, font=font, fill=255, anchor='ls')
        rows = [sum(1 << x for x in range(18) if bitmap.getpixel((x, y)) >= 96) for y in range(21)]
        advance = round(font.getlength(char))
        out.append('{%d,%d,{%s}},' % (ord(char), advance, ','.join('0x%x' % v for v in rows)))
    out += ['};', '#define MENU_GLYPH_COUNT (sizeof menu_glyphs/sizeof menu_glyphs[0])', '#endif']
    (ROOT/'src/platform/menu_font.h').write_bytes(('\n'.join(out)+'\n').encode('utf-8'))
    print('glyphs', len(chars), 'font SHA256', FONT_SHA256)


if __name__ == '__main__':
    main()
